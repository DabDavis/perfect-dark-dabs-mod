#!/usr/bin/env python3
"""Writes port/src/gebeancefixes.h: the GoldenEye XBLA Community Edition's
vertex-colour corrections to the release's HD props and levels, as numbers.

The Community Edition is built into the game (owner, 2026-10-10): its fixes
are rebuilt in our source, never read from its zip, and none of its pictures
or meshes are taken. Where it changed only the colour of a release file's
vertices, the change is a handful of numbers per vertex, and this lists them
byte for byte against the release's own file (gebean.c applies an entry only
where the release's bytes are still the ones listed, so another copy of a file
is left alone).

Inputs: the release (GEFIT_BEAN, files/) and a reference copy of the
Community Edition applied to it (GEFIT_CE, default .xbla-work/ce/filesCE: the
release with CEUpdate/files.diff applied by its own installer). Neither ships.

Only the files below are listed. Every byte that differs must lie in a .gpu
blob that is not a texture's, and in the three colour bytes of a vertex's
ARGB word (the byte before them is its alpha); anything else stops the
generator, so a picture or a vertex position can never slip in. Files the
Community Edition changed otherwise are handled elsewhere or left out - see
CLAUDE-notes/ge-bean.md, "The Community Edition built in".

    gen_cefixtable.py [-o OUT]   (default port/src/gebeancefixes.h; -o - is stdout)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths
import cafftool

CE = os.environ.get('GEFIT_CE', os.path.join(paths.REPO, '..', '.xbla-work', 'ce', 'filesCE'))

# The release's file -> why. Recoloured by the Community Edition and drawn by
# the port (geproptable.h, the HD level); not among the owner's GoldenEye-kept
# taste changes (door tints, hazard strip, Trevelyan's hand, Statue flags,
# table legs) and not tied to one of its new pictures.
FILES = [
    ('new/prop/ammocrate3', 'shaded faces where the release is all white'),
    ('new/prop/cardbox2', 'one corner darker'),
    ('new/prop/gunrunway1', 'the barrel greys where the release is opaque black'),
    ('new/prop/metalchair1', 'white and grey where the release is opaque black'),
    ('new/prop/tuningconsole1', 'black trim where the release is white'),
    ('new/prop/woodlgcrate1', 'lighter shading'),
    ('new/prop/woodsmcrate5', 'lighter shading'),
    ('new/background/complex', "the railings' colours"),
]


def runs(rel, ce):
    """Runs of differing bytes, each (offset, old bytes, new bytes)."""
    out = []
    i = 0
    while i < len(rel):
        if rel[i] == ce[i]:
            i += 1
            continue
        j = i
        while j < len(rel) and rel[j] != ce[j]:
            j += 1
        out.append((i, rel[i:j], ce[i:j]))
        i = j
    return out


def main():
    out = ['// Generated by tools/geconvert/fit/gen_cefixtable.py - do not edit.',
           '// The Community Edition\'s vertex colours: release file, its size, offset, bytes it has, bytes it gets']
    for source, why in FILES:
        rp = os.path.join(paths.BEAN, 'files', source, 'default.bin')
        cp = os.path.join(CE, source, 'default.bin')
        rel = open(rp, 'rb').read()
        ce = open(cp, 'rb').read()
        if len(rel) != len(ce):
            sys.exit('%s: the copies differ in size' % source)
        c = cafftool.Caff(rp)
        tex = {g['asset'] for g in c.files if c.blob(g).startswith(b'texture\0')}
        gpu = []
        for g in c.files:
            s = c.sections[g['sect'] - 1]
            if s['name'].startswith('.gpu') and g['asset'] not in tex:
                gpu.append((s['offset'] + g['start'], s['offset'] + g['start'] + g['size']))
        rs = runs(rel, ce)
        out.append('\t// %s: %s, %d bytes in %d runs' % (source, why, sum(len(r[1]) for r in rs), len(rs)))
        for off, old, new in rs:
            if not any(lo <= off and off + len(old) <= hi for lo, hi in gpu):
                sys.exit('%s: a change at 0x%x outside a vertex blob' % (source, off))
            if len(old) > 3 or rel[off - 1] not in (0xff, 0x7f, 0x00) and len(old) == 3:
                sys.exit('%s: a change at 0x%x is not a vertex colour' % (source, off))
            out.append('\tCEFIX("%s", %d, 0x%x, %d, "%s", "%s"),' % (
                source, len(rel), off, len(old),
                ''.join('\\x%02x' % x for x in old), ''.join('\\x%02x' % x for x in new)))
    paths.output(paths.repo('port/src/gebeancefixes.h')).write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
